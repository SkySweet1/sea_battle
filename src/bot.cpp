static std::vector<Point> targets; // Вектор для хранения координат, по которым бот уже стрелял
/*
static                  означает что переменная живет все время выполнения программы, но доступна только в этом файле (бот.cpp).
std::vector<Point>      это динамический массив который может изменять свой размер - он хранит объекты типа Point которые представляют координаты на игровом поле
targets                 это имя переменной которая будет использоваться для хранения координат, по которым бот уже стрелял - это позволяет боту не стрелять в одно и то же место несколько раз
*/
static Point lastShot = {-1, -1};

static bool initialized = false;

void InitBot() { 
// Функция, которая инициализирует бота, например, может сбросить его внутреннее состояние

    targets.clear(); // Сбросить внутреннее состояние бота, очистив вектор целей
    lastShot = {-1, -1};
    initialized = true;

}
/*
void InitBot()          вызываеться в начале игры в resetGame() для сброса состояния бота

targets.clear()         очищает вектор targets, который хранит координаты, по которым бот уже стрелял

srand(time(0))          инициализирует генератор случайных чисел, используя текущее время в качестве начального значения, чтобы обеспечить разнообразие случайных чисел при каждом запуске программы.
*/

static void AddNeighbors(int x, int y){
// функция для добавления соседних клеток к текущей цели после попадания в корабль. Она принимает координаты x и y, которые представляют текущую цель.

    int dx[] = {1, -1, 0, 0}; // координаты по x
    int dy[] = {0, 0, 1, -1}; // координаты по y
    
    for(int i = 0; i < 4; i++){
        int nx = x + dx[i];
        int ny = y + dy[i];

        if(InBounds(nx, ny)){
            targets.push_back(Point{nx, ny}); // соседние клетки в вектор целей
        }
    }
}
/*
for(int i = 0; i < 4; i++)              цикл для перебора всех четырех направлений (вверх, вниз, влево, вправо) вокруг текущей цели

int nx = x + dx[i];                     вычисляет координату x соседней клетки, добавляя смещение из массива dx к текущей координате x
int ny = y + dy[i];                     вычисляет координату y соседней клетки, добавляя смещение из массива dy к текущей координате y

if(InBounds(nx, ny))                    проверяет, находятся ли координаты соседней клетки в пределах игрового поля, используя функцию InBounds
InBounds(nx, ny)                        функция, которая проверяет, находятся ли координаты (nx, ny) в пределах игрового поля. Она возвращает true, если координаты допустимы, и false в противном случае.

targets.push_back(Point{nx, ny});       если соседняя клетка находится в пределах игрового поля, она добавляется в вектор targets, который хранит координаты, по которым бот уже стрелял. Это позволяет боту не стрелять в одно и то же место несколько раз.
*/

Point GetBotShot() {
// функция которая отдает координаты выстрела бота. Она выбирает случайные координаты для выстрела, избегая уже использованных целей.

    if(!initialized){
        InitBot();
    }


    if(!targets.empty()){
        Point shot = targets.back();        // взять последнюю цель из вектора
        targets.pop_back();                 // удалить ее из вектора
        lastShot = shot;
        return shot;                        // вернуть координаты выстрела
        
    }

    // если нет целей, выбрать случайные координаты
    int x = rand() % 10;                    // предположим, что поле 10x10
    int y = rand() % 10;

    lastShot = {x, y};

    return Point{x, y}; // вернуть случайные координаты
}
/*
if(!targets.empty())                    проверяет, есть ли в векторе targets цели, по которым бот уже стрелял. Если вектор не пустой, бот будет использовать эти цели для выстрела.

Point shot = targets.back();            берет последнюю цель из вектора targets, которая представляет координаты для выстрела
targets.pop_back();                     удаляет эту цель из вектора, чтобы бот не стрелял в одно и то же место несколько раз
return shot;                            возвращает координаты выстрела, которые были взяты из вектора

int x = rand() % 10;                    если вектор targets пустой, бот выбирает случайные координаты для выстрела. 
int y = rand() % 10;                    здесь предполагается, что игровое поле имеет размер 10x10, поэтому координаты генерируются в диапазоне от 0 до 9.
                   
return Point{x, y};                     возвращает случайные координаты для выстрела, если вектор targets был пустой.
*/

void SetBotResult(Result result) {
// функция, которая говорит боту результат выстрела. Она принимает результат выстрела и координаты выстрела, чтобы бот мог обновить свое внутреннее состояние.
 
    if(!initialized){
        InitBot();
    }

    if(result == Result::Hit){
        AddNeighbors(lastShot.x, lastShot.y); // если попадание, добавить соседние клетки к целям
    } else if(result == Result::Sink){
        // если корабль потоплен, можно очистить цели, связанные с этим кораблем
        // в данном примере мы просто очищаем все цели, но можно улучшить логику для более точного определения связанных целей
        targets.clear();
    }
}
/*
if(result == Result::Hit)                   проверяет, был ли результат выстрела попаданием. Если это так, бот добавляет соседние клетки к целям, используя функцию AddNeighbors, чтобы попытаться найти остальные части корабля.
AddNeighbors(shot.x, shot.y)                вызывает функцию AddNeighbors с координатами выстрела, чтобы добавить соседние клетки к целям бота.

else if(result == Result::Sink)             если результат выстрела - потопление корабля, бот может очистить цели, связанные с этим кораблем. В данном примере мы просто очищаем все цели, но можно улучшить логику для более точного определения связанных целей.
targets.clear()                             очищает вектор targets, удаляя все цели, связанные с потопленным кораблем. Это позволяет боту не продолжать стрелять по соседним клеткам, которые уже были проверены.
*/